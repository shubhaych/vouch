// Writes module/src/finance/companies.ts from module/seed/companies.seed.json.
// The seed's inspiredBy field is internal: it is dropped here, so nothing that
// web, worker or the module imports can show it. Run after editing the seed:
//   npx tsx scripts/gen-companies.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
interface SeedProduct { sku: string; name: string; description: string; price_cents: number }
interface SeedCompany { id: number; slug: string; name: string; inspiredBy?: string; category: string; size: number; featured: boolean; tagline: string; products: SeedProduct[] }
const seed = JSON.parse(readFileSync(resolve(root, 'module/seed/companies.seed.json'), 'utf8')) as {
  categories: Record<string, { refund_claim_rate: number; fraud_susceptibility: number }>;
  companies: SeedCompany[];
};

const ids = new Set(seed.companies.map((c) => c.id));
const slugs = new Set(seed.companies.map((c) => c.slug));
if (seed.companies.length !== 100 || ids.size !== 100 || slugs.size !== 100) throw new Error('expected 100 companies with unique ids and slugs');
if (seed.companies.some((c) => c.products.length !== 4)) throw new Error('every company has 4 products');

// Rates as basis points so no float reaches a money path.
const categories = Object.fromEntries(Object.entries(seed.categories).map(([k, v]) => [k, { claimRateBp: Math.round(v.refund_claim_rate * 10_000), fraudSusceptibilityPct: Math.round(v.fraud_susceptibility * 100) }]));
const companies = seed.companies.map(({ inspiredBy: _internal, products, ...c }) => ({
  ...c,
  products: products.map((p) => ({ sku: p.sku, name: p.name, description: p.description, priceCents: p.price_cents })),
}));

const out = `// GENERATED by scripts/gen-companies.ts from module/seed/companies.seed.json. Do not edit.
// 100 fictional partner retailers for the Refund Finance Desk. Names are parodies; no affiliation with any real company.
// The seed's internal-only field is deliberately not carried over.

export interface CompanyProduct { sku: string; name: string; description: string; priceCents: number }
export interface CompanyDef { id: number; slug: string; name: string; category: string; size: number; featured: boolean; tagline: string; products: CompanyProduct[] }
export interface CategoryDef { claimRateBp: number; fraudSusceptibilityPct: number }

export const DISCLAIMER = 'Fictional stores for a hackathon demo. Names are parodies; no affiliation with any real company; no real logos. All data is simulated.';

export const COMPANY_CATEGORIES: Record<string, CategoryDef> = ${JSON.stringify(categories, null, 1)};

export const COMPANIES: readonly CompanyDef[] = ${JSON.stringify(companies, null, 1)};

export const companyById = (id: number): CompanyDef | undefined => COMPANIES[id - 1];
export const companyBySlug = (slug: string): CompanyDef | undefined => COMPANIES.find((c) => c.slug === slug);
`;
writeFileSync(resolve(root, 'module/src/finance/companies.ts'), out);
console.log(`wrote ${companies.length} companies, ${companies.length * 4} products, ${Object.keys(categories).length} categories`);
